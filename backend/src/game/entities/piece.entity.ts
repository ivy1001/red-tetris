export class Piece {
  type: PieceType;
  rotation: number;
  x: number;
  y: number;

  constructor(type: PieceType, x?: number, y = 0, rotation = 0) {
    this.type = type;
    this.x = x ?? Piece.spawnX(type);
    this.y = y;
    this.rotation = rotation % 4;
  }

  static spawnX(type: PieceType): number {
    return type === 'O' ? 4 : 3;
  }

  static randomType(rng: () => number = Math.random): PieceType {
    return PIECE_TYPES[Math.floor(rng() * PIECE_TYPES.length)];
  }

  getMatrix(): number[][] {
    return SHAPES[this.type][this.rotation];
  }

  getColor(): number {
    return COLOR_BY_TYPE[this.type];
  }

  rotated(): Piece {
    return new Piece(this.type, this.x, this.y, (this.rotation + 1) % 4);
  }

  moved(dx: number, dy: number): Piece {
    return new Piece(this.type, this.x + dx, this.y + dy, this.rotation);
  }

  clone(): Piece {
    return new Piece(this.type, this.x, this.y, this.rotation);
  }
}
